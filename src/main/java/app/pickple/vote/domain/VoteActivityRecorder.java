package app.pickple.vote.domain;

/**
 * 새 투표가 일어났다는 사실을 받는 쪽.
 *
 * <p><b>왜 이 인터페이스가 vote 패키지에 있는가</b> — 구현은 {@code badge} 가 하지만
 * 이름과 계약은 <b>쓰는 쪽</b>의 언어로 둔다. 투표 서비스가 아는 것은 "투표 활동을
 * 기록하는 무언가" 이지 뱃지가 아니다. 이렇게 두면 컴파일 의존이
 * {@code badge → vote} 한 방향으로만 흘러, 투표가 보상 도메인을 알지 않아도 된다.
 *
 * <p>스프링 이벤트를 쓰지 않은 이유도 여기 있다. 이벤트의 실익은 의존 방향을 끊는
 * 것인데 그건 이 인터페이스로 이미 끊긴다. 그러면서 이 저장소에 없던 패턴
 * (발행·구독)을 들이지 않고, {@code OnePickService} 가 포인트 지급을 직접 부르는
 * 기존 관행과도 어긋나지 않는다.
 *
 * <p><b>같은 트랜잭션에서 동기로 실행된다.</b> 커밋 후로 미루면 투표는 커밋되고
 * 활동 기록만 유실되어 집계가 영구히 어긋난다 — 그 집계가 일일·연속 판정의 정본이다(R-19).
 */
public interface VoteActivityRecorder {

    /**
     * 오늘의 투표 활동을 기록하고, 뱃지 조건을 다시 판정한다.
     *
     * <p><b>첫 투표에서만 부른다 (R-22).</b> 선택 변경은 새 활동이 아니므로
     * 일별 수를 늘리면 재투표만으로 "하루 20개" 가 채워진다.
     */
    void recordVoteAndEvaluate(Long voterId);
}
