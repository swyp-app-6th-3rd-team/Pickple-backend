package app.pickple.badge.domain;

import java.time.LocalDate;

/**
 * 날짜별 투표 활동 (R-19).
 *
 * <p><b>왜 이 저장소가 있는가</b> — "하루 20개" 와 "7일 연속" 을 {@code vote} 에서 직접
 * 구하면 회원의 투표 이력 전체를 날짜로 묶어야 한다. {@code DATE(created_at)} 은
 * 컬럼을 감싸 인덱스를 무력화하고, 연속 판정은 그 사용자의 투표를 <b>전부</b> 훑는다.
 * 그리고 이 판정은 투표할 때마다 일어난다 — 쓰기 핫패스에 선형 증가 비용이 붙는다.
 *
 * <p>날짜별로 접어 두면 사용자당 "활동한 날" 만큼만 행이 생긴다.
 * 오늘의 투표 수는 행 하나, 연속 일수는 최근 N 행이면 끝난다.
 *
 * <p><b>정책 판단은 하지 않는다.</b> 여기서 나가는 것은 "며칠 연속인가" 같은 사실이고,
 * 그 수가 뱃지 조건을 넘었는지는 {@link Badge} 가 판정한다.
 */
public interface DailyActivityStore {

    /**
     * 그날의 투표 수를 하나 올린다. 그날 첫 투표면 행을 만든다.
     *
     * <p><b>재투표에서는 부르지 않는다 (R-22).</b> 선택을 바꾸는 것은 새 활동이 아니므로
     * 일별 수를 늘리면 "하루 20개" 가 선택 변경만으로 채워진다.
     * 스키마로는 막을 수 없다 — "이 투표가 첫 투표인가" 는 {@code vote} 를 봐야 알고
     * {@code CHECK} 는 다른 행을 보지 못한다. 그래서 호출 지점이 지킨다.
     *
     * <p>날짜를 인자로 받는 이유는 {@code CURRENT_DATE} 가 DB 세션 타임존을 따르기
     * 때문이다. 애플리케이션이 {@code Asia/Seoul} 로 계산해 넘겨야 자정 근처에서
     * 사용자가 보는 하루와 집계의 하루가 갈리지 않는다.
     */
    void increaseVoteCount(Long userId, LocalDate date);

    /**
     * 뱃지 판정에 필요한 세 수를 한 번에 읽는다.
     *
     * <p>세 수를 각각 조회하면 왕복이 셋이고, 그 사이 다른 투표가 끼어들면
     * 서로 다른 시점의 값을 한 판정에 섞게 된다.
     *
     * <p><b>연속 일수의 기준일은 오늘 행의 유무가 정한다.</b> 오늘 투표했으면 오늘부터,
     * 아직 안 했으면 <b>어제부터</b> 거슬러 센다. 어제까지 6일을 채운 사람이 오늘 아침에
     * 미션을 열었을 때 {@code 0/7} 이 나오면 연속이 끊긴 줄 알기 때문이다 — 실제로는
     * 아직 오늘이 남아 있다.
     *
     * <p>이 규칙이 획득 판정을 느슨하게 만들지는 않는다. 판정은 투표 직후에만 도는데
     * 그 시점엔 오늘 행이 반드시 있어서 기준일이 언제나 오늘이다.
     * 곧 "어제부터" 는 <b>표시 경로에서만</b> 관측된다.
     *
     * @param today 오늘 날짜({@code Asia/Seoul}). 일일·연속 판정의 기준점이다
     */
    VoteActivity findActivity(Long userId, LocalDate today);
}
