package app.pickple.badge.domain;

/**
 * 뱃지 획득 조건의 유형 (R-18).
 *
 * <p>정책 요약표 §3 의 "유형" 컬럼을 그대로 옮긴 것이다. 세 유형은 임계값을 비교한다는
 * 점은 같지만 <b>무엇을 세는가</b>가 다르고, 그 차이가 곧 판정 비용의 차이다.
 *
 * <ul>
 *   <li>{@link #TOTAL_VOTE} — 살면서 투표한 총 횟수. 일별 집계의 합계에서 유도한다
 *   <li>{@link #DAILY_VOTE} — <b>하루</b>의 투표 수. 오늘 행 하나면 판정된다
 *   <li>{@link #STREAK_VOTE} — 하루도 빠지지 않은 <b>날 수</b>. 최근 N 행이면 판정된다
 * </ul>
 *
 * <p>뒤의 둘이 {@code vote} 테이블이 아니라 일별 집계를 보는 이유가 R-19 다.
 * 투표 이력을 날짜로 묶으면 투표가 쌓일수록 판정이 느려지는데, 이 판정은
 * 투표할 때마다 일어난다.
 *
 * <p><b>이 enum 은 유형이지 뱃지가 아니다.</b> 뱃지 8종은 {@code badge} 테이블의 행이고,
 * 이름이 바뀌어도 이 세 값은 바뀌지 않는다 — 정책이 예고한 변경은 이름이지 조건이 아니다.
 */
public enum BadgeConditionType {

    /** 누적 투표 횟수. 10 · 100 · 500 · 1,000회 */
    TOTAL_VOTE,

    /** 하루 투표 수. 20 · 30개 */
    DAILY_VOTE,

    /** 연속 참여 일수. 7 · 30일 */
    STREAK_VOTE
}
