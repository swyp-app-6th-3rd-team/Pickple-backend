package app.pickple.badge.domain;

import java.util.Set;

/**
 * 회원이 가진 뱃지.
 *
 * <p>R-17(같은 뱃지를 두 번 획득하지 않는다)의 최종 방어선은
 * {@code UNIQUE(user_id, badge_id)} 다. 판정이 "가졌는지 확인 → 없으면 지급" 형태라
 * 확인과 삽입 사이에 틈이 있고, 동시 투표 둘이 같은 임계값을 함께 넘기면
 * 응용 검증만으로는 뚫린다.
 *
 * <p><b>저장소는 그 사실을 정책으로 해석하지 않는다</b> (ADR-0019).
 * "삽입됐는가" 만 알리고, 그것이 재획득 시도라는 판단은 서비스가 한다.
 */
public interface UserBadgeStore {

    /** 이 회원이 가진 뱃지 id 집합. 획득/미획득을 가르는 데 쓴다. */
    Set<Long> findOwnedBadgeIds(Long userId);

    /**
     * 아직 없으면 지급하고, 이미 있으면 아무것도 하지 않는다 (R-17).
     *
     * <p><b>확인 후 삽입이 아니라 원자적 삽입이어야 한다.</b> 조회로 거른 뒤 저장하면
     * 동시 요청이 모두 "없다" 를 보고 모두 삽입을 시도한다 — 실측했다.
     * 같은 회원이 8개 요청으로 임계값을 동시에 넘겼을 때 <b>1건만 성공하고 7건이
     * 무결성 위반으로 500</b> 이 됐다. 뱃지는 투표의 부가 효과인데 그 실패가
     * 투표를 통째로 죽인 것이다.
     *
     * <p>무결성 예외를 잡아 삼키는 것도 답이 아니다. 이 지급은 투표 트랜잭션 안에서
     * 일어나는데, {@code @Transactional} 안에서 무결성 예외가 나면 스프링이 트랜잭션을
     * rollback-only 로 표시한다. 예외를 삼켜 "이미 있으니 정상" 으로 처리해도 커밋 시점에
     * {@code UnexpectedRollbackException} 이 나고 투표가 실패한다.
     *
     * <p>그래서 <b>예외가 애초에 나지 않게</b> 한다. 중복이 "실패" 가 아니라
     * "아무것도 바꾸지 않음" 이 되면 트랜잭션이 살아 있다.
     *
     * <p>반환값이 없는 이유 — "이번에 새로 받았는가" 를 저장소가 알려주려면 영향 행 수를
     * 해석해야 하는데 그 값은 드라이버·설정에 따라 갈린다(ERD 3차 §1.3).
     * 그 판단은 지급 전 보유 목록을 아는 서비스가 한다.
     */
    void grantIfAbsent(Long userId, Long badgeId);
}
