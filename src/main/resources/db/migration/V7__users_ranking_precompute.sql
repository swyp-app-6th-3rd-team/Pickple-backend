-- 작성자 랭킹 사전 계산 컬럼 (ADR-0028).
--
-- 순위는 "앞에 몇 명이 있는가" 라 전역 집계다. 조회 시점에 세면 회원 전체를 정렬해야 하고
-- (200k 기준 97.6ms/조각), 인덱스로 줄일 수 있는 비용이 아니다 — idx_users_ranking 이
-- covering 으로 걸린 뒤에도 20만 행 정렬과 윈도 집계가 그대로 남는다.
-- 그래서 배치가 미리 계산해 두고 목록 조회는 작성자 조인에서 읽기만 한다.
--
-- NULL 은 "아직 산정되지 않음" 이다. 가입 직후 다음 배치까지, 그리고 탈퇴자가 이 상태다.
-- 0 이나 "전체 회원 수 + 1" 같은 값을 채우지 않는다 — 지어낸 순위는 실제 꼴찌와 구분되지 않는다.
--
-- 정렬 기준은 users.point 이지만 그 정본은 point_history 원장이다 (R-14).
-- users.point 는 원장에서 유도한 캐시이고, 같은 배치가 원장 합계로 먼저 채운다.
ALTER TABLE users
    ADD COLUMN ranking INT UNSIGNED DEFAULT NULL
        COMMENT 'TOP 피커 순위. 배치 사전계산값이며 NULL 은 미산정 (ADR-0028)';
