-- 랭킹 목록 조회용 인덱스 (이슈 #26).
--
-- V7 은 ranking 컬럼만 추가했다. 배치가 쓰기만 하던 동안에는 인덱스가 필요 없었지만
-- (전체를 다시 계산하므로 어차피 전 행을 훑는다), 목록 조회가 이 컬럼을 정렬 키로
-- 쓰기 시작하면 이야기가 달라진다.
--
-- 실측 (회원 200,000 · MySQL 8.4 · RankingListRepository 의 실제 쿼리)
--
--   인덱스 없음   첫 조각 LIMIT 11   43.5 ms   Table scan 200,000행 + Sort
--                 깊은 조각          33.1 ms   Table scan 200,000행 + Sort
--   인덱스 있음   첫 조각 LIMIT 11    0.070 ms  Index range scan (NULL < ranking) 11행
--                 깊은 조각           0.045 ms  Index range scan (150000 < ranking) 11행
--
-- 실행계획이 원인을 정확히 말한다. ranking 에 인덱스가 없으면 MySQL 은 정렬을 위해
-- 회원 전체를 읽어야 하고, 그 비용은 LIMIT 11 과 무관하게 회원 수에 비례한다.
-- 이건 ADR-0028 이 사전 계산으로 걷어낸 바로 그 Θ(전체 회원 수) 가
-- 조회 쪽으로 되돌아온 것이다 — 순위를 미리 계산해 두고도 그 값을 찾는 데
-- 전체를 훑으면 사전 계산의 이득이 사라진다.
--
-- 왜 idx_users_ranking (point DESC, created_at) 으로는 안 되는가.
-- 그 인덱스는 배치가 순위를 매길 때 쓰는 순서이지 조회 커서가 쓰는 순서가 아니다.
-- 커서를 (point, created_at, id) 튜플로 바꿔 그 인덱스를 태워도 봤는데
-- 오히려 느렸다(114 ms) — 튜플의 세 번째 키 id 가 인덱스에 없어 행 값 비교가
-- 범위 시작점으로 접히지 못하고, 인덱스를 위에서부터 훑으며 거르기 때문이다.
-- 조각이 깊을수록 훑는 양이 늘어 OFFSET 과 같은 성질이 된다(149,456행 스캔).
--
-- ranking 하나로 커서를 세우는 근거는 그 값이 ROW_NUMBER() 가 만든 전순서라는 것이다.
-- 200k 시드에서 COUNT(DISTINCT ranking) = 200,000 으로 중복이 없음을 확인했다.
-- 동률이 없으므로 조각 경계에서 행이 새지 않아 튜플로 묶을 필요가 없다.
--
-- NULL 은 인덱스에 들어가지만 목록 조회가 ranking IS NOT NULL 로 거르므로
-- 범위 스캔의 시작점이 된다. 미산정·탈퇴 회원이 많아도 조회는 그들을 건너뛴다.
ALTER TABLE users
    ADD KEY idx_users_ranking_order (ranking);
