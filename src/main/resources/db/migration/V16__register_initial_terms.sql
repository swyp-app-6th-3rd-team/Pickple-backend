## 제6장 기타

### 제19조(회사의 의무)

1. 회사는 관계 법령과 본 약관이 금지하거나 미풍양속에 반하는 행위를 하지 않으며, 계속적이고 안정적으로 서비스를 제공하기 위하여 최선을 다하여 노력합니다.

1. 회사는 회원이 안전하게 서비스를 이용할 수 있도록 개인정보 보호를 위한 보안 시스템을 갖추어야 하며 개인정보처리방침을 공시하고 준수합니다.

1. 회사는 서비스 이용과 관련하여 회원으로부터 제기된 의견이나 불만이 정당하다고 인정할 경우에는 이를 처리하여야 하며, 처리에 장기간이 소요되는 경우 회원에게 그 사유와 처리 일정을 안내합니다.

### 제20조(손해배상)

1. 회사는 무료로 제공되는 서비스와 관련하여 관련 법령에 특별한 규정이 없는 한 회원에게 어떠한 손해도 배상하지 않습니다. 다만, 회사의 고의 또는 중대한 과실로 인한 손해의 경우에는 그러하지 아니합니다.

1. 회원이 본 약관을 위반하거나 콘텐츠 게시와 관련하여 타인의 권리(초상권, 저작권, 명예 등)를 침해함으로써 회사 또는 제3자에게 손해가 발생한 경우, 해당 회원은 이로 인해 발생한 손해를 배상할 책임이 있습니다.

### 제21조(면책조항)

1. 회사는 천재지변 또는 이에 준하는 불가항력으로 인하여 서비스를 제공할 수 없는 경우 서비스 제공에 관한 책임이 면제됩니다.

1. 회사는 회원의 귀책사유로 인한 서비스 이용의 장애에 대하여 책임을 지지 않습니다.

1. 회사는 회원이 서비스와 관련하여 게재한 정보, 자료, 사실의 신뢰도, 정확성 등 내용에 대해서는 책임을 지지 않습니다.

1. 회사는 회원 간 또는 회원과 제3자 간에 서비스를 매개로 발생한 분쟁(초상권 침해, 명예훼손, 저작권 침해 등을 포함)에 대해 개입할 의무가 없으며, 이로 인한 손해를 배상할 책임도 없습니다. 다만 회사는 원활한 해결을 위하여 필요한 범위 내에서 지원할 수 있습니다.

1. 회사는 무료로 제공하는 서비스 이용과 관련하여 관계 법령에 특별한 규정이 없는 한 책임을 지지 않습니다.

### 제22조(저작권의 귀속 및 이용제한)

1. 회사가 작성한 저작물(서비스 UI, 로고, 회사가 직접 제작한 콘텐츠 등)에 대한 저작권 및 기타 지적재산권은 회사에 귀속됩니다.

1. 회원은 서비스를 이용함으로써 얻은 정보 중 회사에게 지적재산권이 귀속된 정보를 회사의 사전 승낙 없이 복제, 송신, 출판, 배포, 방송 기타 방법에 의하여 영리 목적으로 이용하거나 제3자에게 이용하게 하여서는 안 됩니다.

### 제23조(분쟁해결 및 재판관할)

1. 회사와 회원은 서비스와 관련하여 발생한 분쟁을 원만하게 해결하기 위하여 필요한 모든 노력을 하여야 합니다.

1. 제1항의 노력에도 불구하고 분쟁이 해결되지 않을 경우 양 당사자는 「민사소송법」상의 관할 법원에 소를 제기할 수 있습니다.

1. 회사와 회원 간에 제기된 소송에는 대한민국 법을 적용합니다.

