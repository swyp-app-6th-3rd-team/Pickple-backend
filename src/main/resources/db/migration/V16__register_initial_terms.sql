## 제1장 총칙

### 제1조(목적)

본 약관은 PickPle(이하 "회사"라 합니다)이 제공하는 PickPle 애플리케이션 및 관련 제반 서비스(이하 "서비스"라 합니다)의 이용과 관련하여 회사와 회원 간의 권리, 의무 및 책임사항, 기타 필요한 사항을 규정함을 목적으로 합니다.

### 제2조(정의)

1. "서비스"란 회사가 제공하는 사진 기반 투표·랭킹·커뮤니티 서비스로서, 회원이 이용할 수 있는 모든 서비스를 의미합니다.

1. "회원"이란 본 약관에 동의하고 카카오, 애플 등 소셜 계정을 연동하여 회사와 서비스 이용계약을 체결한 자를 말합니다.

1. "게스트"란 회원가입 없이 임시로 서비스의 일부 기능을 이용하는 자를 말하며, 본 약관에서 "회원"에 관한 규정은 성질에 반하지 않는 한 게스트에게 준용됩니다.

1. "콘텐츠"란 회원이 서비스를 이용하면서 게시 또는 등록하는 사진, 이미지, 게시글, 댓글, 투표 카드 등 모든 정보 또는 자료를 말합니다.

1. "투표 카드"란 회원이 투표를 목적으로 등록하는 사진 및 관련 정보의 게시 단위를 말합니다.

1. "게시물"이란 회원이 서비스를 이용함에 있어 서비스 상에 게시한 부호·문자·음성·음향·화상·동영상 등의 정보 형태의 글, 사진, 댓글 등 일체의 자료를 의미합니다.

1. "포인트"란 회원의 서비스 내 활동(투표 참여, 게시물 작성, 미션 달성, 랭킹 획득 등)에 따라 회사가 회원에게 부여하는 서비스 내 전용 가상의 자산을 말합니다.

1. "랭킹 서비스"란 회원 또는 콘텐츠의 인기도, 득표수 등을 기준으로 순위를 산정하여 노출하는 "TOP 리커" 등의 서비스를 말합니다.

### 제3조(약관의 게시와 개정)

1. 회사는 본 약관의 내용을 회원이 쉽게 알 수 있도록 서비스 초기 화면 또는 [마이페이지 > 약관 및 정책] 메뉴에 게시합니다.

1. 회사는 「약관의 규제에 관한 법률」, 「정보통신망 이용촉진 및 정보보호 등에 관한 법률」 등 관계 법령을 위반하지 않는 범위에서 본 약관을 개정할 수 있습니다.

1. 회사가 약관을 개정할 경우에는 적용일자 및 개정사유를 명시하여 현행 약관과 함께 적용일자 최소 7일 전부터(회원에게 불리하거나 중대한 사항의 변경은 30일 전부터) 서비스 내 공지사항을 통해 공지합니다.

1. 회원이 개정약관의 적용일 이후에도 서비스를 계속 이용하는 경우 개정약관에 동의한 것으로 간주합니다. 회원이 개정약관에 동의하지 않는 경우 이용계약을 해지(회원 탈퇴)할 수 있습니다.

### 제4조(약관의 해석)

본 약관에서 정하지 아니한 사항이나 해석에 대해서는 관계 법령 및 회사가 정한 서비스의 세부 운영정책, 이용안내 등에 따릅니다.

