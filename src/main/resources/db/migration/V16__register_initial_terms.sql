## 제2조 개인정보의 보관기간 및 이용기간

1. 회원의 개인정보는 수집목적 또는 제공받은 목적의 달성, 동의 철회 또는 회원 탈퇴 시까지 보관 및 이용됩니다. 다만, 개인정보의 계속 보관·이용에 관한 별도의 동의를 얻은 경우 또는 관계 법령에 따라 보관 의무가 주어진 경우에는 예외로 합니다.

   - 회원가입 및 서비스 이용에 관한 기록: 회원 탈퇴일까지

1. 관계법령에 따라 보관 의무가 주어진 경우(단, 아래에 한정되지 않음)

   - 소비자의 불만 또는 분쟁처리에 관한 기록: 3년 (전자상거래 등에서의 소비자보호에 관한 법률)

   - 웹사이트 및 앱 방문·접속 기록: 3개월 (통신비밀보호법)

1. 회사 내부 방침에 의한 경우

   - 회사의 이용약관이나 법령을 위반하여 서비스에 손해를 끼친 회원의 불법적인 서비스 이용 등에 관한 기록

1. 회사는 정보 복구 요청 대응 또는 다른 회원 보호를 위하여 내부 방침에 따라 다음과 같이 회원의 개인정보를 보관합니다.

   - 회사의 이용약관이나 법령을 위반한 회원의 개인정보: 사법기관에 수사 의뢰를 하거나 다른 회원을 보호할 목적으로 최대 5년간 보관 (세부 기준은 제11조 참조)

