## 제6조 개인정보의 자동 수집 장치의 설치·운영 및 그 거부에 관한 사항

1. **쿠키(Cookie)란?** 쿠키란 웹/앱 서버가 브라우저 또는 애플리케이션에 보내어 저장했다가 서버의 부가적인 요청이 있을 때 다시 서버로 보내주는 문자열 정보(텍스트 파일)를 의미합니다.

1. **회사의 쿠키 정책**: 회사가 운영하는 서비스는 회원의 정보를 저장하고 수시로 찾아내는 쿠키를 설치·운용하고 있습니다. 회원이 서비스에 접속하면 회원의 기기에 저장된 쿠키의 내용을 읽어 추가 정보 입력 없이 서비스를 제공할 수 있습니다.

1. **쿠키를 통해 수집하는 정보 및 이용 목적**

   - 회사가 쿠키를 통해 수집하는 정보는 회원의 고유번호에 한하며, 그 외의 다른 정보는 수집하지 않습니다.

   - 개인의 관심 분야에 따라 차별화된 정보(추천 투표, 인기 게시글 등) 제공

   - 이용자의 접속 빈도 또는 머문 시간 등을 분석하여 취향과 관심 분야를 파악, 최적화된 광고 등 맞춤형 정보 제공

   - 서비스 이용 내역을 추적·분석하여 향후 개인 맞춤 서비스 제공 및 서비스 개편 등의 척도로 활용

1. **거부 방법**: 회원은 다음과 같은 방법으로 쿠키 설치에 대한 선택권을 가지고 있으며, 쿠키 허용 및 거부를 설정할 수 있습니다. 다만 쿠키 설치를 거부할 경우 서비스 이용이 불편해지거나 로그인이 필요한 일부 서비스 이용이 어려울 수 있습니다.

   - Android: 설정 > 앱 > PickPle > 저장공간/캐시 관리에서 쿠키·캐시 삭제

   - iOS: 설정 > Safari > 고급 > 모든 쿠키 차단 (앱 내 웹뷰 이용 시 해당)

