## 제4장 콘텐츠(게시물)

### 제12조(게시물의 게시)

1. 회원은 서비스 내에서 투표 카드, 게시글, 댓글 등의 형태로 콘텐츠를 게시할 수 있습니다.

1. 회원이 게시하는 사진에 회원 본인 또는 제3자의 얼굴 등 초상이 포함되는 경우, 해당 초상권자로부터 게시 및 서비스 내 활용(투표, 노출, 공유 등)에 관한 동의를 받을 책임은 게시자 본인에게 있습니다. 회사는 게시물에 포함된 초상권, 저작권 등 제3자의 권리에 대하여 사전에 실질적으로 심사하지 않으며, 이와 관련하여 발생하는 분쟁 및 책임은 게시자 본인에게 있습니다.

1. 회원은 자신이 게시한 콘텐츠에 대한 권리와 책임을 부담하며, 콘텐츠가 관계 법령 및 본 약관을 위반하지 않도록 하여야 합니다.

### 제13조(게시물에 대한 권리 및 이용허락)

1. 회원이 서비스 내에 게시한 콘텐츠에 대한 저작권 등 지적재산권은 원칙적으로 해당 콘텐츠를 게시한 회원에게 귀속됩니다.

1. 회원은 서비스 내에 콘텐츠를 게시함으로써 회사에 대하여 다음 각 호의 목적을 위하여 무상으로, 국내외에서 콘텐츠를 사용, 복제, 수정, 편집, 전시, 전송, 배포할 수 있는 비독점적 이용을 허락한 것으로 봅니다.

   1. 서비스의 제공, 운영, 개선, 홍보(단, 회원 개인을 식별할 수 있는 형태의 별도 상업적 광고 활용은 회원의 사전 동의를 받습니다)

   1. 서비스 내 다른 회원에 대한 노출 및 투표·댓글·원픽 기능 제공

   1. 서비스의 오류 수정, 통계 작성, 부정이용 방지를 위한 분석

1. 회원은 언제든지 자신이 게시한 콘텐츠를 삭제할 수 있으며, 콘텐츠 삭제 시 제2항에 따른 이용허락도 함께 종료됩니다. 다만, 다른 회원이 이미 저장, 캡처, 공유한 콘텐츠 사본 및 검색엔진 등에 노출된 캐시 정보에 대해서는 회사가 통제할 수 없습니다.

### 제14조(게시물의 관리)

1. 회원의 게시물이 다음 각 호에 해당하는 내용을 포함한다고 판단되는 경우, 회사는 관계 법령에 위반되지 않는 범위에서 회원에게 사전 통지 없이 해당 게시물을 삭제, 임시조치(블라인드) 또는 이동할 수 있습니다.

   1. 다른 회원 또는 제3자를 비방하거나 명예를 훼손하는 내용

   1. 다른 회원 또는 제3자의 초상권, 저작권 등 지적재산권을 침해하는 내용

   1. 공공질서 및 미풍양속에 위반되는 내용, 음란물 또는 청소년에게 유해한 내용

   1. 미성년자로 추정되는 자가 포함된 부적절하거나 선정적인 사진

   1. 범죄와 결부된다고 인정되는 내용, 도박 관련 내용

   1. 스팸성 게시물, 도배, 무단 광고·홍보성 게시물

   1. 투표 조작, 어뷰징 등 서비스 운영을 방해하는 내용

   1. 회사 또는 제3자의 개인정보를 무단으로 노출하는 내용

   1. 기타 관계 법령 또는 본 약관에 위반된다고 판단되는 내용

1. 회사는 「정보통신망 이용촉진 및 정보보호 등에 관한 법률」 등 관계 법령에 따라 권리를 침해받았음을 주장하는 자의 요청이 있는 경우 해당 게시물에 대해 임시조치를 취할 수 있습니다.

1. 회원은 본조에 따른 조치에 대하여 고객센터를 통해 이의를 제기할 수 있습니다.

### 제15조(신고 및 차단)

1. 회원은 다른 회원의 게시물, 댓글 또는 계정이 제15조 각 호에 해당한다고 판단하는 경우 서비스 내 신고 기능을 통해 회사에 신고할 수 있습니다.

1. 회원은 다른 회원의 계정을 차단할 수 있으며, 차단된 계정의 게시물 및 활동은 차단한 회원에게 노출되지 않습니다.

1. 회사는 접수된 신고의 내용을 검토하여 경고, 게시물 삭제, 이용 제한 등 필요한 조치를 취할 수 있으며, 반복적이거나 허위로 신고 기능을 남용하는 경우 해당 회원의 서비스 이용을 제한할 수 있습니다.

1. 신고 처리와 관련하여 수집되는 정보의 보관 기간은 개인정보처리방침 제11조에 따릅니다.

