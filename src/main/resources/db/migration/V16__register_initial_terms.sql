## 제2장 서비스 이용계약

### 제5조(이용계약의 성립)

1. 이용계약은 이용자가 본 약관 및 개인정보처리방침에 동의하고, 카카오·애플 등 회사가 지원하는 소셜 계정을 통해 회원가입을 신청한 후, 회사가 이러한 신청에 대하여 승낙함으로써 성립합니다.

1. 이용자는 소셜 계정 연동 대신 게스트로 서비스 일부 기능(둘러보기 등)을 우선 체험할 수 있으며, 게스트로서 이용 가능한 서비스의 범위는 회원과 다르게 제한될 수 있습니다.

1. 회사는 다음 각 호에 해당하는 가입 신청에 대해서는 승낙하지 않거나 사후에 이용계약을 해지할 수 있습니다.

   1. 가입 신청자가 본 약관에 의하여 이전에 회원자격을 상실한 적이 있는 경우

   1. 실명이 아니거나 타인의 명의(SNS 계정 포함)를 이용한 경우

   1. 허위의 정보를 기재하거나 회사가 제시하는 내용을 기재하지 않은 경우

   1. 기타 회원으로 등록하는 것이 서비스 운영상 현저히 지장이 있다고 판단되는 경우

### 제6조(회원정보의 변경)

회원은 [마이페이지 > 수정] 메뉴를 통해 닉네임, 프로필 사진 등 개인정보를 열람하고 수정할 수 있습니다. 다만, 서비스 관리를 위해 필요한 일부 정보(가입 경로 등)는 수정이 제한될 수 있습니다.

### 제7조(계정의 관리 및 책임)

1. 회원의 계정에 대한 관리 책임은 회원 본인에게 있으며, 이를 제3자가 이용하도록 하여서는 안 됩니다.

1. 회원은 연동한 소셜 계정(카카오, 애플)의 정보 유출, 부정 이용 등을 인지한 경우 즉시 회사에 통지하고 회사의 안내에 따라야 합니다.

1. 제2항의 통지를 하지 않거나 통지 후 회사의 안내에 따르지 않아 발생한 불이익에 대하여 회사는 책임을 지지 않습니다.

