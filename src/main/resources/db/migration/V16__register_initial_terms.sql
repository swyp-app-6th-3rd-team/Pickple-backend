1. 회사는 제1항에 따른 이용제한 조치를 하는 경우 그 사유, 기간 등을 회원에게 사전 또는 사후에 통지합니다. 다만, 긴급하게 조치할 필요가 있는 경우에는 사후 통지할 수 있습니다.

1. 회원은 본조에 따른 이용제한 조치에 대하여 회사가 정한 절차에 따라 이의를 신청할 수 있습니다. 회사는 이의가 정당하다고 인정되는 경우 즉시 서비스 이용을 재개합니다.

### 제18조(계약해지 및 이용제한)

1. 회원은 언제든지 [마이페이지 > 설정 > 회원 탈퇴] 메뉴를 통해 이용계약 해지(회원 탈퇴)를 신청할 수 있으며, 회사는 관계 법령이 정하는 바에 따라 이를 즉시 처리합니다.

1. 회원 탈퇴 시 회원의 개인정보는 개인정보처리방침에 따라 처리되며, 탈퇴 회원이 작성한 게시물은 별도로 삭제를 요청하지 않는 한 서비스 운영 및 다른 회원의 이용 편의를 위하여 삭제되지 않고 남아있을 수 있습니다(단, 게시물 내 회원의 개인정보는 비식별 처리됩니다).

1. 회사는 회원이 제17조를 위반하거나 영구이용정지 사유에 해당하는 경우 회원의 동의 없이 이용계약을 해지할 수 있습니다.

