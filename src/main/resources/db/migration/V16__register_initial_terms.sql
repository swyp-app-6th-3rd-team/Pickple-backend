## 제5장 회원의 의무 및 이용제한

### 제16조(회원의 의무)

회원은 다음 각 호의 행위를 하여서는 안 됩니다.

1. 회원가입 신청 또는 정보 변경 시 허위 내용을 등록하는 행위, 타인의 SNS 계정 등 개인정보를 도용하는 행위

1. 회사가 게시한 정보를 무단으로 변경하거나 회사가 정한 정보 이외의 정보 등을 송신 또는 게시하는 행위

1. 회사와 기타 제3자의 저작권 등 지적재산권을 침해하는 행위

1. 회사 및 기타 제3자의 명예를 손상시키거나 업무를 방해하는 행위

1. 본인 또는 제3자의 초상권을 침해하거나 제3자의 동의 없이 그 초상이 포함된 사진을 게시하는 행위

1. 외설·음란하거나 폭력적인 내용, 미성년자에게 유해한 내용을 게시하는 행위

1. 다른 회원을 성적으로 대상화하거나 성희롱·스토킹하는 행위

1. 무단 광고성·홍보성 정보(스팸)를 전송하거나 게시물을 반복 등록(도배)하는 행위

1. 서비스의 안정적 운영을 방해할 목적으로 다량의 정보를 전송하거나, 컴퓨터 바이러스·악성코드를 유포하는 행위

1. 비인가 프로그램(매크로, 자동화 봇 등)을 사용하여 투표, 좋아요, 댓글, 포인트 적립 등을 조작하는 행위

1. 하나의 신체(본인)로 다수의 계정을 생성하여 부정하게 서비스를 이용하는 행위

1. 회사의 승인을 받지 않고 다른 회원의 개인정보를 수집, 저장, 공개하는 행위

1. 회사 직원이나 운영자를 사칭하거나 이를 도용하는 행위, 운영진을 협박하는 행위

1. 관계 법령 및 본 약관에서 금지하는 기타 위법 또는 부당한 행위

### 제17조(서비스 이용제한)

1. 회사는 회원이 제17조 각 호의 금지행위를 하거나 관계 법령 및 본 약관을 위반한 경우, 위반의 정도에 따라 경고, 콘텐츠 삭제, 일부 기능 제한, 일시정지, 영구이용정지 등의 조치를 취할 수 있습니다. 제재의 세부 기준은 다음 각 호와 같으며, 구체적인 적용은 위반의 경중 및 반복 여부에 따라 회사가 합리적으로 판단합니다.

