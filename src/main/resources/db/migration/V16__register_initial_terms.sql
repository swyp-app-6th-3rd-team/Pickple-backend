### 3. 회원이 업로드하는 콘텐츠(사진 등)에 관한 특칙

1. 회원이 투표 카드 등록, 게시글·댓글 작성 등을 위하여 직접 업로드하는 사진·이미지에는 회원 본인 또는 제3자의 얼굴, 신체 등 초상이 포함될 수 있습니다.

1. 이러한 사진·이미지는 회원이 자신의 의사에 따라 자발적으로 게시하는 콘텐츠이며, 게시 즉시 다른 이용자에게 공개되어 투표·댓글·원픽 등 서비스 내 상호작용의 대상이 됩니다.

1. 회원이 본인이 아닌 제3자가 포함된 사진을 업로드하는 경우, 해당 제3자로부터 초상권 이용에 관한 동의를 받을 책임은 게시자 본인에게 있으며, 이를 위반하여 발생하는 민형사상 책임 또한 게시자 본인에게 있습니다. 회사는 이러한 사진의 적법한 취득 및 게시 여부를 사전에 실질적으로 심사하지 않으며, 다만 신고 접수 시 제11조(게시물의 관리) 등 관련 절차에 따라 조치합니다.

1. 미성년자로 추정되는 인물이 포함된 부적절한 사진, 선정적·음란한 사진, 그 밖에 관계 법령을 위반하는 사진은 사전 통지 없이 삭제될 수 있으며, 관련 법령에 따라 수사기관에 신고되는 등 조치될 수 있습니다.

1. 회원이 콘텐츠를 삭제하더라도 다른 회원이 이를 캡처·공유하는 등의 행위까지 회사가 통제할 수는 없으므로, 회원은 콘텐츠 게시 시 이 점에 유의해야 합니다.

### 4. 서비스 이용 과정에서 자동으로 생성되어 수집되는 정보

1. 스마트폰 및 스마트 OS 탑재 모바일 기기(Tablet PC 등): 모델명, 기기별 고유번호(UDID, IMEI 등), 기기 식별자, OS 정보, 이동통신사, 카카오/애플 광고 ID

1. 기타 정보: 서비스 이용(정지) 기록, 접속 로그, 쿠키, 접속 IP 정보, 앱 크래시(오류) 로그

1. 자동 생성에 의해 수집되는 정보는 원칙적으로 개인을 식별할 수 없는 형태이며, 회사는 수집된 정보를 활용하여 개인을 별도로 식별하기 위한 활동을 하지 않습니다.

1. 자동 생성에 의해 수집되는 정보에 대한 내용과 수집 거부 방법은 제6조 및 제7조를 참고하시기 바랍니다.

1. 기기 식별자는 서비스의 정상적인 운영 목적으로만 사용되며, 광고·마케팅·사용자 추적 등의 목적으로는 사용되지 않습니다.

### 5. 개인정보 수집 방법

- 회원가입(카카오·애플 로그인) 및 서비스 이용 과정에서 이용자가 개인정보 수집에 동의하고 직접 정보를 입력하거나 SNS 계정 연동을 통해 수집

- 프로필 설정, 게시글·댓글·투표 카드 등록 등 서비스 이용 과정에서 이용자가 직접 제공

- 고객문의를 통한 상담 과정에서 수집

- 신고·차단 기능 이용 과정에서 신고자 및 피신고자 관련 정보 수집

- 기기정보와 같은 생성정보는 앱 이용 과정에서 자동으로 생성되어 수집

- 온라인·오프라인에서 진행되는 이벤트 등을 통해 추가 개인정보 수집: 해당 수집 시점에 별도의 개인정보 수집·이용 동의를 받습니다.

### 6. 민감정보의 미수집 원칙

회사는 기본적 인권 침해의 우려가 있는 개인정보(인종 및 민족, 사상 및 신조, 출신지 및 본적지, 정치적 성향 및 범죄기록, 건강상태 및 성생활 등)를 요구하지 않으며, 위 항목 이외에 다른 어떠한 목적으로도 수집·이용하지 않습니다.

