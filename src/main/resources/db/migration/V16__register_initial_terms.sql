## 제3장 서비스의 제공 및 이용

### 제8조(서비스의 제공 및 변경)

1. 회사는 다음과 같은 서비스를 제공합니다.

   1. 사진 기반 투표 카드 등록 및 투표 참여 서비스

   1. 게시글·댓글 작성, 원픽 등 커뮤니티 서비스

   1. 미션 수행 및 포인트 적립 서비스

   1. 인기 투표·랭킹(TOP 피커) 서비스

   1. 프로필 관리 및 알림(푸시) 서비스

   1. 기타 회사가 추가 개발하거나 다른 회사와의 제휴를 통해 회원에게 제공하는 일체의 서비스

1. 회사는 서비스의 내용, 운영상·기술상 필요에 따라 제공하는 서비스의 전부 또는 일부를 변경할 수 있으며, 이 경우 변경 사유 및 내용, 제공일자 등을 사전에 공지합니다. 다만, 긴급한 오류 수정 등 불가피한 경우 사후 공지할 수 있습니다.

### 제9조(서비스 이용시간 및 중단)

1. 서비스는 회사의 업무상 또는 기술상 특별한 지장이 없는 한 연중무휴, 1일 24시간 제공함을 원칙으로 합니다.

1. 회사는 다음 각 호의 경우 서비스 제공을 일시적으로 중단할 수 있습니다.

   1. 서비스용 설비의 점검, 보수, 교체 등 공사가 부득이한 경우

   1. 정전, 서비스 설비의 장애 또는 서비스 이용의 폭주 등으로 정상적인 서비스 제공이 어려운 경우

   1. 기간통신사업자가 전기통신서비스를 중지하는 등 불가항력적 사유가 발생한 경우

1. 회사는 제2항에 따른 서비스 중단의 경우 사전에 공지하는 것을 원칙으로 하며, 부득이하게 사전 공지가 불가능한 경우 사후에 공지할 수 있습니다.

### 제10조(정보의 제공 및 광고의 게재)

1. 회사는 서비스 운영과 관련하여 서비스 화면, 이메일, 푸시 알림 등의 방법으로 회원에게 각종 정보 및 광고를 제공할 수 있습니다. 다만, 회원은 관계 법령에 따른 거래 관련 정보 및 고객문의 등을 제외하고는 언제든지 앱 내 설정을 통해 마케팅성 정보 및 광고성 알림의 수신을 거부할 수 있습니다.

1. 회사는 서비스 상에 게재되어 있는 광고를 통해 이용자가 광고주와 거래하는 것과 관련하여 어떠한 책임도 지지 않으며, 해당 거래로 발생하는 문제는 회원과 광고주 간에 해결하여야 합니다.

### 제11조(포인트 및 랭킹 서비스)

1. 회사는 회원의 댓글 참여 및 작성 등 서비스 내 활동에 따라 포인트를 부여할 수 있습니다.

1. 포인트는 현금으로 환급되지 않으며, 원칙적으로 타인에게 양도, 매매, 담보 제공할 수 없습니다.

1. 회원 탈퇴, 부정한 방법(어뷰징, 다중계정, 자동화 프로그램 사용 등)으로 취득한 포인트는 사전 통지 없이 소멸 또는 회수될 수 있습니다.

1. 회사는 사업 운영상 또는 정책상의 필요에 따라 포인트 제도의 내용을 변경하거나 제도 자체를 폐지할 수 있으며, 이 경우 사전에 공지합니다.

1. "TOP 리커" 등 랭킹은 댓글 활동 지표 등을 기준으로 자동 산정되며, 회사는 어뷰징이 확인된 회원 또는 콘텐츠를 랭킹에서 제외하거나 순위를 조정할 수 있습니다. 랭킹 산정 기준은 서비스 운영상 사전 공지 후 변경될 수 있습니다.

