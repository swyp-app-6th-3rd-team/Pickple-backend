## 제5조 정보주체의 권리와 그 행사방법

1. 회원은 언제든지 다음 각 호의 개인정보 보호 관련 권리를 행사할 수 있습니다.

   1. 개인정보 열람 요구

   1. 오류 등이 있을 경우 정정 요구

   1. 삭제 요구

   1. 처리정지 요구

1. 제1항에 따른 권리 행사를 하려는 회원은 제10조에 기재된 고객센터에 웹 문의, 서면, 전자우편의 방법으로 본인의 개인정보의 조회·정정·삭제를 요청할 수 있습니다. 고객센터는 회원의 권리 행사에 대하여 지체없이 조치하고 처리 결과를 안내합니다.

1. 회원은 앱 내 [마이페이지 > 프로필 관리] 및 [마이페이지 > 설정] 메뉴에서 등록된 닉네임, 프로필 사진 등 개인정보를 직접 조회·수정할 수 있으며, 즉시 결과를 확인할 수 있습니다.

1. 회원이 위 제2항, 제3항의 처리 결과에 대해 이의가 있을 경우 고객센터에 연락할 수 있으며, 회사는 이의제기 내용을 검토하여 처리 결과를 안내합니다.

1. 회원은 서비스 이용계약 해지(회원 탈퇴)를 통하여 개인정보의 수집 및 이용 동의를 철회할 수 있습니다. 탈퇴는 [마이페이지 > 설정 > 회원 탈퇴] 메뉴를 통해 직접 처리할 수 있습니다.

1. 개인정보의 정정을 요청하신 경우에는 정정을 완료하기 전까지 회사는 당해 개인정보를 이용 또는 제공하지 않습니다. 또한 잘못된 개인정보를 제3자에게 이미 제공한 경우에는 정정 처리결과를 제3자에게 지체 없이 통지하여 정정이 이루어지도록 합니다. 단, 다음의 경우에는 예외적으로 개인정보의 열람 및 정정을 제한할 수 있습니다.

   1. 본인 또는 제3자의 생명, 신체, 재산 또는 권익을 현저하게 해할 우려가 있는 경우

   1. 서비스 제공자의 업무에 현저한 지장을 미칠 우려가 있는 경우

   1. 법령에 위반하는 경우

1. 회사는 삭제 또는 회원 탈퇴 요청이 있을 경우 개인정보 및 개인 데이터를 삭제 또는 제거합니다. 단, 회사는 제2조 및 제11조에 명시된 바와 같이 법령 또는 부정이용 방지 목적에 따른 기간 동안 회원의 개인정보를 보관할 수 있습니다.

1. 회사는 회원이 타인의 개인정보(SNS 계정 등)를 도용하여 회원가입 등을 하였음을 알게 된 때 지체없이 해당 계정에 대한 서비스 이용정지 또는 회원탈퇴 및 개인정보 삭제 등 필요한 조치를 취합니다.

