## 제4조 개인정보의 제3자 제공

회사는 회원의 개인정보를 본 개인정보처리방침에서 명시된 범위를 초과하여 이용하거나 회원의 동의 없이 본 개인정보처리방침에 명시된 제공 대상자 외의 제3자(타인 또는 타기업, 기관)에 제공하지 않습니다. 다만, 다음 각 호의 어느 하나에 해당하는 경우에는 예외로 합니다.

1. 관계법령에 의하여 수사, 재판 또는 행정상의 목적으로 관계기관으로부터 요구가 있는 경우

1. 신용정보의 이용 및 보호에 관한 법률, 전기통신기본법, 전기통신사업법, 소비자보호법 등 기타 관계법령에서 정한 절차에 따른 요청이 있는 경우

1. 재난, 감염병, 급박한 생명·신체 위험을 초래하는 사건·사고, 급박한 재산 손실 등의 긴급상황이 발생하는 경우

1. 다른 회원의 권리를 침해하는 신고·게시물 관련 분쟁 해결을 위하여 필요한 최소한의 범위 내에서, 관계 법령이 정한 절차에 따라 정보가 제공되는 경우

회사는 영업의 전부 또는 일부를 양도하거나, 합병·상속 등으로 서비스제공자의 권리·의무를 이전·승계하는 경우 개인정보 보호와 관련한 회원의 권리를 보장하기 위하여 반드시 그 사실을 회원에게 사전 통지합니다.

