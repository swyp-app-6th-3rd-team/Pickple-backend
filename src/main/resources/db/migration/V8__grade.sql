-- 도달한 최고 등급 (ADR-0030).
--
-- 등급의 승급 조건은 이 테이블이 아니라 코드(Grade enum)가 갖는다.
-- 기준 테이블을 만들면 정책 요약표 §2 와 DB 두 곳이 정본이 되고, 복제본은 어긋날 수 있다.
-- 5개 고정값이고 릴리스 주기에 묶여 있어 코드가 정본에 더 가깝다.
--
-- 이 컬럼이 저장하는 것은 기준이 아니라 "어디까지 올라갔는가" 라는 사실 하나다.
--
-- 왜 저장하는가 — R-16(등급은 내려가지 않는다)을 명시로 만들기 위해서다.
-- 오늘은 포인트가 줄어들 경로가 없어(PointReason 은 +10·+5 뿐, 원장에 삭제 경로 없음,
-- R-06 이 원픽 취소를 금지) 계산값이 단조 증가하고, 이 컬럼은 아무 차이를 만들지 않는다.
-- 저장하지 않으면 R-16 은 "회수 경로가 없어서 저절로 참" 인 상태로 남고,
-- 회수가 생기는 날 등급이 조용히 내려간다 — 컴파일도 되고 테스트도 초록인 채로.
--
-- NULL 을 두지 않는다. 정책표가 "LV.1 가입 시 기본 부여" 라고 정했으므로
-- 미산정 상태가 존재하지 않는다. V7 의 ranking 이 NULL(배치 전)을 갖는 것과 다르다 —
-- 등급은 가입 즉시 확정된다.
--
-- 기존 회원도 DEFAULT 1 로 채워진다. 이미 조건을 넘긴 회원은 다음 조회에서
-- 원장 판정이 더 높은 값을 내므로 그때 올라간다 (승급은 조회 시점에 판정한다).
-- 마이그레이션에서 원장을 훑어 미리 채우지 않는 이유는, 그 계산이 곧
-- 애플리케이션이 하는 판정과 같은 것이라 두 곳에 같은 규칙을 두게 되기 때문이다.
ALTER TABLE users
    ADD COLUMN highest_grade TINYINT UNSIGNED NOT NULL DEFAULT 1
        COMMENT '도달한 최고 등급 레벨 1~5. 내려가지 않는다 (R-16, ADR-0030)',

    -- 승급 조건은 코드가 갖지만, 레벨 범위는 스키마가 지킨다.
    -- 애플리케이션 버그로 0 이나 9 가 들어가면 Grade.ofLevel 이 예외를 던지는데,
    -- 그 시점엔 이미 저장된 뒤라 해당 회원의 조회가 계속 실패한다. 쓰기를 막는 편이 낫다.
    ADD CONSTRAINT ck_users_highest_grade CHECK (highest_grade BETWEEN 1 AND 5);
